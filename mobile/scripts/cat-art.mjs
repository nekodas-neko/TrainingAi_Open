// The collection's drawn cats and its pen backdrop, as plain SVG the phone can draw.
//
// The web app serves these from `public/cats/`. They are shapes with fill and stroke attributes plus
// three things react-native-svg cannot draw: a `<style>` block of CSS keyframes (tail, paws, blink),
// a one-pixel rim `<filter>`, and `class` / `style` hooks for those. This strips exactly those, so
// what is left is the still pose of the same art. Run `node scripts/build-cat-art.mjs` to rewrite
// `src/features/collection/art/catArt.generated.ts` after the art in `public/cats/` changes; a test
// fails when the two have drifted.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const artDir = resolve(root, '../public/cats');
export const outFile = resolve(root, 'src/features/collection/art/catArt.generated.ts');
/** The four classes the four ladders are drawn as, six tiers each, and the one backdrop the pen uses. */
export const classes = ['tank', 'ranger', 'cleric', 'rogue'];
export const tiers = [1, 2, 3, 4, 5, 6];
export const scenes = ['meadow'];

export function stripArt(svg) {
  return svg
    .replace(/<style>[\s\S]*?<\/style>/g, '')
    .replace(/<filter\b[\s\S]*?<\/filter>/g, '')
    .replace(/\sfilter="[^"]*"/g, '')
    .replace(/\sclass="[^"]*"/g, '')
    .replace(/\sstyle="[^"]*"/g, '')
    .replace(/<defs>\s*<\/defs>/g, '')
    .trim();
}

export function buildModule(dir = artDir) {
  const entries = [
    ...classes.flatMap((c) => tiers.map((t) => [`${c}-${t}`, `${c}-${t}`])),
    ...scenes.map((s) => [`scene-${s}`, `scene-${s}`]),
  ];
  const body = entries
    .map(
      ([key, file]) =>
        `  '${key}': ${JSON.stringify(stripArt(readFileSync(resolve(dir, `${file}.svg`), 'utf8')))},`,
    )
    .join('\n');
  return `// Generated by scripts/build-cat-art.mjs from public/cats/. Do not edit.\nexport const catArt: Record<string, string> = {\n${body}\n};\n`;
}

export function writeModule() {
  writeFileSync(outFile, buildModule());
}
