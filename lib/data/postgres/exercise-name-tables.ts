import { lockLiftWrites } from '../../coach/lock-wait'

type SqlTx = { execute: (query: ReturnType<typeof sql>) => Promise<{ rows: unknown[]; rowCount?: number | null }> }

/**
 * Every table with an `exercise_name` column, and what a library rename does about it. The schema
 * test (`__tests__/exercise-rename-repoints-4001.test.ts`) scans `schema.ts` and fails when a table is missing here,
 * so adding a name-keyed table forces a decision about renames instead of silently orphaning rows
 * (which is how `exercise_estimates` was missed, then migration 164 had to repoint it by hand).
 *
 * - `repointed`: `repointStoredExerciseNames`, `renameSessionExercises` or the log update in the adapter
 *   move these rows to the new name in the rename's transaction. Only tables with a unique key that
 *   includes `exercise_name` can abort a rename on a collision: `personal_records`,
 *   `exercise_estimates` and `exercise_preferences`, each resolved per person below.
 * - `not-per-user`: catalogue media keyed by name; regenerated by the admin, not repointed.
 * - `history`: a record of what a person answered at a point in time, kept under the name it was
 *   answered with. A rename does not rewrite it; readers match on `exercise_id` first, which a
 *   rename does not change, and use the name only as the fallback key.
 */
export const EXERCISE_NAME_TABLES = {
  session_exercises: { disposition: 'repointed', how: 'renameSessionExercises, which also bumps the programs it touched; cannot collide (unique only on live (session_id, position), the name is not in a key)' },
  exercise_logs: { disposition: 'repointed', how: 'adapter rename paths, stamped with clientEditedAt; cannot collide (no unique key on the name)' },
  personal_records: { disposition: 'repointed', how: 'repointStoredExerciseNames; per person: a lone old-name row moves, on a collision the target row is raised to the better figure and the old-name row is then deleted (owner-approved, #4004), only if that person has no log left under the old name and the survivor holds at least its figure; the survivor takes the leftover\'s library id when it has none (only the renamed exercise\'s own) or ends on the renamed exercise\'s id when it held another\'s, and, on a tie, the earlier date; one of two deletes in a rename (the other is exercise_estimates)' },
  exercise_estimates: { disposition: 'repointed', how: 'repointStoredExerciseNames; per person: a lone old-name row moves; on a collision the target name\'s row survives and the old-name row is then deleted (owner-approved, #4035 answer 1 A), in the same transaction. Every figure here is one the person typed (nothing recomputes it from logs), so the survivor takes the leftover\'s figure and updated_at when the leftover was typed strictly later, and takes its library id by the personal_records rule; a tie or an older leftover changes nothing on the survivor. The other delete in a rename is personal_records' },
  exercise_preferences: { disposition: 'repointed', how: 'repointStoredExerciseNames; the live row wins a collision, the other is tombstoned, and the library id is carried onto the survivor' },
  set_hr_stats: { disposition: 'repointed', how: 'repointStoredExerciseNames; cannot collide (keyed by set_log_id, no unique key on the name)' },
  weekly_checkin_exercises: { disposition: 'history', how: 'a past check-in\'s answer, kept as answered (#3890). Cannot collide: the name is unique only within one check-in. Readers match exercise_id first. Open for step 2 of #3890: the writer must fill exercise_id, or repoint these rows here, so a lift renamed without an id is not orphaned in history. The parent weekly_checkins also holds two lift names this registry\'s schema scan does not see (pain_exercise_name, swap_exercise_name: not named exercise_name): both are kept as answered too, so a still-open pain or swap offer can carry the old name after a rename and readers match pain_exercise_id / swap_exercise_id first' },
  exercise_gif_cache: { disposition: 'not-per-user', how: 'a cache; adminUpdateExercise clears the old name and the route re-sets the new one' },
  exercise_media: { disposition: 'not-per-user', how: 'catalogue media keyed by (name, gender); regenerated by the admin' },
} as const satisfies Record<string, { disposition: 'repointed' | 'not-per-user' | 'history'; how: string }>

/**
 * Move the per-user rows keyed by exercise name from `oldName` to `newName`, inside the caller's
 * rename transaction. Rows of every user follow, like `session_exercises` and `exercise_logs`: the
 * library name is global, so a user left on the old name would point at an exercise that no longer
 * exists.
 *
 * A user who already has a row under `newName` is a collision on the (user, name) unique key. The
 * only hard deletes are the leftover `personal_records` row and the leftover `exercise_estimates` row
 * (both below); nothing else is deleted:
 *  - `exercise_estimates`: the `newName` row survives and the `oldName` row is deleted in the same
 *    transaction (#4035 answer 1 A, owner-approved 22 Nov). The table has no tombstone column and
 *    the key is (user, name), so the old row cannot be hidden. It would stay readable by an
 *    exercise created later under the old name. Unlike a personal record, an estimate is NEVER
 *    derived from logs: it is the starting 1RM the person typed in the program builder, so a deleted
 *    value cannot be recomputed. The survivor therefore takes the leftover's figure, with its
 *    `updated_at`, when the leftover was typed strictly later (the person's latest entry is kept);
 *    on a tie or an older leftover the survivor is unchanged, as migration 164 resolved it. Its
 *    library id follows the personal_records rule. Only the old-name rows of people who collided in
 *    THIS rename go: their rows are locked first (user, then name order) and a removed row of anyone
 *    else throws and rolls the rename back. A person with only an old-name row has it moved.
 *  - `exercise_preferences`: the live row wins. If only the `oldName` row is live it is copied onto
 *    the (tombstoned) `newName` row. The `oldName` row is then tombstoned with `deleted_at`, and its
 *    `exercise_id` is cleared so the tombstone cannot hold the (user, exercise_id) unique slot.
 *  - `personal_records`: a person with a row under only `oldName` has it moved. A person with both
 *    keeps the better figure on the `newName` row (raised only when the old one is higher by more than
 *    0.005, with its `achieved_at`, as migration 164 step (b)); a tie keeps the target's figure. The
 *    table has no tombstone column and the key is (user, name), so the old row cannot be hidden or
 *    renamed away.
 *
 *    THE LEFTOVER (#4004, option A, owner-approved 22 Nov). Left in place it would be counted by
 *    `lib/achievements.ts`, listed by `listRecentPersonalRecords` / `listPersonalRecordsDated`, and
 *    compared against by `upsertPersonalRecordIfBetter` if the old name were ever used again. So the
 *    rename deletes it, in the same transaction, with one `DELETE` guarded by three conditions: it is
 *    the old name's row of a person who collided in THIS rename; that person has no `exercise_logs`
 *    left under the old name (`NOT EXISTS`, so a row with supporting logs is never removed); and the
 *    survivor holds at least its figure (same 0.005 tie band as the raise). Every deleted user is
 *    checked against the set of colliders read up front; a stray one throws and rolls the rename back.
 *    In the same statement, for exactly the rows it deleted, the survivor takes the leftover's library
 *    id when it has none (only the renamed exercise's own id), is set to the renamed exercise's id
 *    when it held a different one (#4021: a stale id would report another exercise's type), and on a tie the EARLIER `achieved_at`
 *    (a record's date is when its best was first reached, which is what a rebuild from logs gives;
 *    migration 164 and `upsertPersonalRecordIfBetter` keep the incumbent's date on a tie instead).
 *    The other delete in a rename is the leftover `exercise_estimates` row (below). A device that has not synced still holds the row until its
 *    next pull, which replaces its synced bests with the server's complete set.
 *
 *    CONCURRENT LOGGING. The rename first locks both rows of each colliding person (`FOR UPDATE`, in
 *    user then name order). The log path is two transactions: `logExerciseAndSets` inserts the log and
 *    commits, taking no `personal_records` lock; then `upsertPersonalRecordIfBetter` locks the record
 *    row the same way and writes it. So the rename serialises with the record step, not with the log
 *    insert. What stays open: a log insert still uncommitted when the delete runs is invisible to the
 *    `NOT EXISTS`, so the record is removed and the log lands under the old name. Its own record step
 *    then runs right after its commit and, finding no row, writes one from that log (a log that
 *    qualifies for a record always gets one); a log that does not qualify (a deload) never had one.
 *    The window is one insert-to-commit of a single exercise's log, only for a person who collides,
 *    on a rename of an exercise they are logging at that moment. Not closed by a table lock, on purpose.
 *
 *    WHO CAN TRIGGER IT. `renameExercise` (a person renaming their own custom exercise) and
 *    `adminUpdateExercise` both end here, and the repoint covers EVERY user's rows, exactly as it
 *    moves every user's logs. So a person renaming their own exercise can also remove another user's
 *    leftover old-name record, if that user collided on the same name pair.
 *  - `set_hr_stats` has no name uniqueness, so every row simply moves.
 */
/**
 * #4082 review 2: a rename's preference statements update two rows of one person when that person holds a
 * row under BOTH names (the live source, and the target it collides with): the target first (the revive),
 * then the source. A weekly check-in that saves both lifts updates them in LIFT order, so the two met in a
 * cycle (the check-in holding the source and wanting the target, the rename the other way round): 40P01,
 * one side answers 500. Every writer that holds more than one of a person's rows takes the person's
 * lift-write lock first, so the rename does for each such person: in user order, before any other
 * statement of the rename (the callers run this first), waiting holding nothing, bounded by `lockWait`
 * (a timeout is the rename's existing "busy" refusal, nothing renamed).
 *
 * Only people with a row under both names need it: any other person has at most one preference row that
 * a rename touches, and a writer holding one row wants no other row the rename holds. A row created under
 * the new name between this read and the statements below is not covered (it needs a first-ever save of
 * a lift under the new name in that window).
 */
export async function lockCollidingLiftWrites(tx: SqlTx, oldName: string, newName: string): Promise<void> {
  if (oldName === newName) return
  const users = (await tx.execute(sql`
    SELECT DISTINCT s.user_id FROM exercise_preferences s
      JOIN exercise_preferences t ON t.user_id = s.user_id AND t.exercise_name = ${newName}
     WHERE s.exercise_name = ${oldName}
     ORDER BY s.user_id
  `)).rows as { user_id: string }[]
  for (const u of users) await lockLiftWrites(tx as never, u.user_id)
}

export async function repointStoredExerciseNames(tx: SqlTx, oldName: string, newName: string): Promise<void> {
  if (oldName === newName) return

  // Lock the colliding people's rows under both names before anything is read or decided, in one fixed
  // order (user, then name) so two renames cannot take them crosswise. `upsertPersonalRecordIfBetter`
  // (the second half of every logged exercise) takes the same row lock with `SELECT ... FOR UPDATE`, so
  // the two serialise here. The statements below then run after any such wait, each on a fresh READ
  // COMMITTED snapshot, so the "no log under the old name" check sees what the wait let commit. What it
  // cannot see is a log insert that is still open: `logExerciseAndSets` takes no record lock (see the
  // doc comment above for what that leaves).
  await tx.execute(sql`
    SELECT p.id FROM personal_records p
    WHERE p.exercise_name IN (${oldName}, ${newName})
      AND p.user_id IN (
        SELECT s.user_id FROM personal_records s
        WHERE s.exercise_name = ${oldName}
          AND EXISTS (SELECT 1 FROM personal_records t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName}))
    ORDER BY p.user_id, p.exercise_name
    FOR UPDATE
  `)
  // The people who hold a record under both names: the only ones whose old-name row may be removed
  // below. Read after the lock and before the moves, which change who still has an old-name row.
  const colliders = new Set(((await tx.execute(sql`
    SELECT s.user_id FROM personal_records s
    WHERE s.exercise_name = ${oldName}
      AND EXISTS (SELECT 1 FROM personal_records t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)).rows as { user_id: string }[]).map(r => r.user_id))

  // Raise the target record where the person's old-name record is the better one (164 step (b)).
  await tx.execute(sql`
    UPDATE personal_records t
    SET estimated_1rm = s.estimated_1rm, achieved_at = s.achieved_at
    FROM personal_records s
    WHERE s.user_id = t.user_id AND s.exercise_name = ${oldName} AND t.exercise_name = ${newName}
      AND s.estimated_1rm > t.estimated_1rm + 0.005
  `)
  // A person with no row under the new name just has the old one moved.
  await tx.execute(sql`
    UPDATE personal_records s SET exercise_name = ${newName}
    WHERE s.exercise_name = ${oldName}
      AND NOT EXISTS (SELECT 1 FROM personal_records t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)
  // Where both existed, the survivor now holds the better figure and the old-name row is a leftover
  // (#4004, owner-approved 22 Nov). It is removed only when ALL of these hold, in the statement itself:
  //  - it is the old name's row (the only rows still under it are the colliders', the rest just moved);
  //  - the person has no log left under the old name (the caller has just moved them, and a row that
  //    still has supporting logs is never removed, whatever else is true);
  //  - the survivor's figure is at least the leftover's. "At least" carries the same 0.005 tolerance
  //    as the raise above, so the tie band leaves no leftover; a leftover that is better by more than
  //    that would already have been copied onto the survivor, so one still better is left alone.
  // What the removed row still owes the survivor goes across in the same statement, for exactly the
  // rows it removed: its library id, when the survivor has none and the id is the renamed exercise's
  // own (never another exercise's); and, when the two figures tie, the EARLIER date, because a
  // record's date is when its best was first reached (what `reconcilePersonalRecord` rebuilds:
  // best figure, earliest log).
  // `reconcilePersonalRecord` is not used: it runs on the pool, outside this transaction, and it
  // re-derives from logs (an upsert when any exist) rather than asserting the three conditions.
  const removed = (await tx.execute(sql`
    WITH gone AS (
      DELETE FROM personal_records s
      WHERE s.exercise_name = ${oldName}
        AND NOT EXISTS (
          SELECT 1 FROM exercise_logs el
          JOIN workout_sessions ws ON ws.id = el.workout_session_id
          WHERE ws.user_id = s.user_id AND el.exercise_name = ${oldName}
        )
        AND EXISTS (
          SELECT 1 FROM personal_records t
          WHERE t.user_id = s.user_id AND t.exercise_name = ${newName}
            AND t.estimated_1rm + 0.005 >= s.estimated_1rm
        )
      RETURNING s.user_id, s.exercise_id, s.estimated_1rm, s.achieved_at
    ), carried AS (
      UPDATE personal_records t
      SET exercise_id = CASE
            WHEN t.exercise_id IS NULL
              THEN CASE WHEN g.exercise_id = (SELECT l.id FROM exercise_library l WHERE l.name = ${oldName}) THEN g.exercise_id END
            ELSE COALESCE((SELECT l.id FROM exercise_library l WHERE l.name = ${oldName}), t.exercise_id)
          END,
          achieved_at = CASE WHEN abs(t.estimated_1rm - g.estimated_1rm) <= 0.005
                             THEN LEAST(t.achieved_at, g.achieved_at) ELSE t.achieved_at END
      FROM gone g
      WHERE t.user_id = g.user_id AND t.exercise_name = ${newName}
      RETURNING t.id
    )
    SELECT user_id FROM gone
  `)).rows as { user_id: string }[]
  // Affected-row check: only a person who collided in this rename may lose a row. Anything else
  // throws, which rolls the whole rename back.
  for (const r of removed) {
    if (!colliders.has(r.user_id)) throw new Error('Rename would remove a record of a person who had no collision')
  }

  // Estimates (#4035). Lock both rows of each colliding person first, in one fixed order (user, then
  // name), after the personal_records locks above and before anything here moves. The only other
  // writer, `upsertExerciseEstimate`, is a single `INSERT ... ON CONFLICT DO UPDATE` that takes the
  // same row lock, so it serialises here: a write that lands first is seen by the carry below, one
  // that waits re-checks the key after the rename commits.
  await tx.execute(sql`
    SELECT p.id FROM exercise_estimates p
    WHERE p.exercise_name IN (${oldName}, ${newName})
      AND p.user_id IN (
        SELECT s.user_id FROM exercise_estimates s
        WHERE s.exercise_name = ${oldName}
          AND EXISTS (SELECT 1 FROM exercise_estimates t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName}))
    ORDER BY p.user_id, p.exercise_name
    FOR UPDATE
  `)
  const estimateColliders = new Set(((await tx.execute(sql`
    SELECT s.user_id FROM exercise_estimates s
    WHERE s.exercise_name = ${oldName}
      AND EXISTS (SELECT 1 FROM exercise_estimates t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)).rows as { user_id: string }[]).map(r => r.user_id))

  // A person with no estimate under the new name just has the old one moved.
  await tx.execute(sql`
    UPDATE exercise_estimates e SET exercise_name = ${newName}, updated_at = now()
    WHERE e.exercise_name = ${oldName}
      AND NOT EXISTS (
        SELECT 1 FROM exercise_estimates t WHERE t.user_id = e.user_id AND t.exercise_name = ${newName}
      )
  `)
  // Where both existed, the old-name row is a leftover (#4035, owner-approved 22 Nov). Its only
  // condition is the collision itself: the person has a row under the new name. Nothing about logs
  // applies, an estimate is typed and is not backed by them. What the leftover still owes the
  // survivor goes across in the same statement, for exactly the rows removed: its figure and
  // `updated_at` when it was typed strictly later than the survivor's, and its library id by the
  // `personal_records` rule (#4021).
  const removedEstimates = (await tx.execute(sql`
    WITH gone AS (
      DELETE FROM exercise_estimates s
      WHERE s.exercise_name = ${oldName}
        AND EXISTS (
          SELECT 1 FROM exercise_estimates t
          WHERE t.user_id = s.user_id AND t.exercise_name = ${newName}
        )
      RETURNING s.user_id, s.exercise_id, s.estimated_1rm, s.updated_at
    ), carried AS (
      UPDATE exercise_estimates t
      SET exercise_id = CASE
            WHEN t.exercise_id IS NULL
              THEN CASE WHEN g.exercise_id = (SELECT l.id FROM exercise_library l WHERE l.name = ${oldName}) THEN g.exercise_id END
            ELSE COALESCE((SELECT l.id FROM exercise_library l WHERE l.name = ${oldName}), t.exercise_id)
          END,
          estimated_1rm = CASE WHEN g.updated_at > t.updated_at THEN g.estimated_1rm ELSE t.estimated_1rm END,
          updated_at = GREATEST(t.updated_at, g.updated_at)
      FROM gone g
      WHERE t.user_id = g.user_id AND t.exercise_name = ${newName}
      RETURNING t.id
    )
    SELECT user_id FROM gone
  `)).rows as { user_id: string }[]
  // Affected-row check: only a person who collided in this rename may lose a row. Anything else
  // throws, which rolls the whole rename back.
  for (const r of removedEstimates) {
    if (!estimateColliders.has(r.user_id)) throw new Error('Rename would remove an estimate of a person who had no collision')
  }

  // Revive a tombstoned target with the live source's choices, so the user's live preference survives.
  // The revived row's own library id is cleared: a tombstone can still hold an id, possibly another
  // exercise's, and the revived row now carries the source's choices, so it must point at the renamed
  // exercise (taken from the source below) or at nothing, never at a different exercise.
  await tx.execute(sql`
    UPDATE exercise_preferences t
    SET rep_min = s.rep_min, rep_max = s.rep_max, rest_sec = s.rest_sec,
        next_load_step = s.next_load_step, sets_delta = s.sets_delta, one_shot_set_at = s.one_shot_set_at,
        source = s.source, deleted_at = NULL, updated_at = now(),
        exercise_id = NULL
    FROM exercise_preferences s
    WHERE s.user_id = t.user_id AND s.exercise_name = ${oldName} AND t.exercise_name = ${newName}
      AND s.deleted_at IS NULL AND t.deleted_at IS NOT NULL
  `)
  // The library id of each colliding source, read before the tombstone below clears it: the survivor
  // takes it over afterwards. (Not in one statement: the (user, exercise_id) unique index is checked
  // row by row, so the survivor cannot take the id while the source still holds it.)
  const carried = (await tx.execute(sql`
    SELECT s.user_id, s.exercise_id FROM exercise_preferences s
    WHERE s.exercise_name = ${oldName} AND s.exercise_id IS NOT NULL
      AND EXISTS (SELECT 1 FROM exercise_preferences t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)).rows as { user_id: string; exercise_id: string }[]
  // A source that has a target: tombstone it (the target holds the live choice now).
  await tx.execute(sql`
    UPDATE exercise_preferences s
    SET deleted_at = COALESCE(s.deleted_at, now()), exercise_id = NULL, updated_at = now()
    WHERE s.exercise_name = ${oldName}
      AND EXISTS (SELECT 1 FROM exercise_preferences t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)
  // The survivor keeps its own library id if it has one, otherwise takes the source's.
  for (const c of carried) {
    await tx.execute(sql`
      UPDATE exercise_preferences SET exercise_id = ${c.exercise_id}, updated_at = now()
      WHERE user_id = ${c.user_id} AND exercise_name = ${newName} AND exercise_id IS NULL
    `)
  }
  // Every other source row just moves.
  await tx.execute(sql`
    UPDATE exercise_preferences s SET exercise_name = ${newName}, updated_at = now()
    WHERE s.exercise_name = ${oldName}
      AND NOT EXISTS (SELECT 1 FROM exercise_preferences t WHERE t.user_id = s.user_id AND t.exercise_name = ${newName})
  `)

  await tx.execute(sql`UPDATE set_hr_stats SET exercise_name = ${newName} WHERE exercise_name = ${oldName}`)
}
