-- LA-114 — `oura_daytime_stress_buckets.bucket_start` never held a bucket start. It holds the
-- bucket's MIDPOINT, and has since the table was created.
--
-- `daytimeHrvEstimatesPerBucket` returns `t = bStart + bucketMs / 2`
-- (packages/shared/src/health/daytime-hrv-model.ts), `scoreStressPoints` carries `t` through, and
-- `run.ts` writes `new Date(p.tMs)` straight into this column. Stored timestamps therefore sit on a
-- :15/:45 grid rather than :00/:30.
--
-- Migration 212's own header is where the mistake is written down — "the bucket's own start
-- instant, from the series' `t`". The series' `t` is not the start. The column was named for what
-- its author believed `t` was.
--
-- WHY RENAME RATHER THAN RE-STAMP THE VALUES. The stored value is not wrong: the midpoint is a
-- legitimate representative of a 30-minute bucket, and the one consumer (the stress-day chart)
-- plots it as a point in time, which is correct either way. Only the NAME lies. Shifting 672 rows
-- back by 15 minutes would move a chart that is currently right in order to fix a string, and would
-- be a data migration rather than a reversible rename.
--
-- The harm this removes is specific and already realised: a join written the obvious way — matching
-- these timestamps against any other 30-minute series on the epoch grid — returns ZERO rows, which
-- reads as "no overlapping data" rather than "the join is 15 minutes out". That is a silent wrong
-- answer, and it cost an hour during TN-39's validation on 2026-09-16 before the :15 grid was
-- noticed. A comment would not have stopped it; the name is what a query is written from.
--
-- Reversible and drops nothing: `ALTER TABLE ... RENAME COLUMN bucket_mid TO bucket_start` undoes
-- it. The paired `claude_ro` view regeneration is the NEXT migration — a base-table rename does not
-- rename a view's output column, so without it `claude_ro` would keep exposing `bucket_start` while
-- the table said `bucket_mid`, which is the same lie with an extra step.

ALTER TABLE oura_daytime_stress_buckets RENAME COLUMN bucket_start TO bucket_mid;
