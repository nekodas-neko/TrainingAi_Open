// Writes scripts/tuning/blank-exercise-names-4129.sql. The SQL's character class is generated from the
// SAME regex `hasVisibleCharacter` uses (packages/shared/src/validation/visible-name.ts), because
// Postgres has no \p{…}. A test fails when the committed SQL differs from this output, so the count
// and the predicate cannot drift.
//
//   node scripts/tuning/blank-exercise-names-4129.mjs           print the SQL
//   node scripts/tuning/blank-exercise-names-4129.mjs --write   regenerate the committed file
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { invisibleNameClassSql } from '../../packages/shared/src/validation/visible-name.ts'

export function renderSql() {
  return `-- GENERATED by scripts/tuning/blank-exercise-names-4129.mjs; do not edit by hand (a test compares them).
-- #4129: how many stored lift names have no visible character. READ-ONLY, COUNTS ONLY: no name, id or
-- user is selected, so nothing here can be pasted into an issue by mistake. Nothing is renamed or deleted.
--
--   psql "$DATABASE_URL" -f scripts/tuning/blank-exercise-names-4129.sql          (local)
--   the same text through /api/admin/db-query                                      (production, the Orchestrator)
--
-- The character class is the one \`hasVisibleCharacter\` refuses (packages/shared/src/validation/visible-name.ts:
-- every default-ignorable code point, every format and control character, whitespace, the Braille
-- blank and the Hangul fillers), enumerated from that same regex into code-point ranges, because
-- Postgres has no \\p{...}. It is exact for the Unicode version of the Node that generated it; a name
-- is blank when nothing else is left after removing the class.
WITH invisible(re) AS (
  VALUES ('[${invisibleNameClassSql()}]')
),
lib AS (
  SELECT count(*) AS exercises_total,
         count(*) FILTER (WHERE regexp_replace(l.name, i.re, '', 'g') = '') AS exercises_blank
  FROM claude_ro.exercise_library l CROSS JOIN invisible i
),
lifts AS (
  SELECT count(*) AS session_lifts_total,
         count(*) FILTER (WHERE regexp_replace(e.exercise_name, i.re, '', 'g') = '') AS session_lifts_blank
  FROM claude_ro.session_exercises e CROSS JOIN invisible i
  WHERE e.deleted_at IS NULL
)
SELECT lib.exercises_total, lib.exercises_blank, lifts.session_lifts_total, lifts.session_lifts_blank
FROM lib CROSS JOIN lifts;
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = renderSql()
  if (process.argv.includes('--write')) {
    writeFileSync(fileURLToPath(new URL('./blank-exercise-names-4129.sql', import.meta.url)), sql)
  } else process.stdout.write(sql)
}
